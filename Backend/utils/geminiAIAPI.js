
import "dotenv/config";

const GEMINI_API_URL =
    "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.6-flash:generateContent";

// Gemini API helper
const getGeminiAPIResponse = async (message, attachments = []) => {
    if (!process.env.GEMINI_API_KEY) {
        throw new Error("GEMINI_API_KEY is missing.");
    }

    if (!Array.isArray(attachments)) {
        throw new Error("Invalid attachments.");
    }

    // Keep total raw attachments within a conservative limit.
    const totalSize = attachments.reduce(
        (total, file) => total + file.size,
        0
    );

    if (totalSize > 15 * 1024 * 1024) {
        throw new Error("Combined attachment size exceeds 15 MB.");
    }

    // Build Gemini content parts
    const parts = [];

    if (message && message.trim()) {
        parts.push({
            text: message.trim(),
        });
    } else {
        parts.push({
            text: "Please analyze the attached file(s).",
        });
    }

    // Add images and PDFs
    for (const file of attachments) {
        if (!file.buffer || !file.mimetype) {
            throw new Error("Invalid uploaded file.");
        }

        const isPDF = file.mimetype === "application/pdf";

        // Allow only commonly supported image formats and PDF
        const allowedImageTypes = [
            "image/jpeg",
            "image/png",
            "image/webp",
            "image/heic",
            "image/heif",
        ];

        if (!isPDF && !allowedImageTypes.includes(file.mimetype)) {
            throw new Error(
                `Unsupported file type: ${file.mimetype}`
            );
        }

        parts.push({
            inlineData: {
                mimeType: file.mimetype,
                data: file.buffer.toString("base64"),
            },
        });
    }

    const options = {
        method: "POST",
        headers: {
            "Content-Type": "application/json",
            "x-goog-api-key": process.env.GEMINI_API_KEY,
        },
        body: JSON.stringify({
            contents: [
                {
                    role: "user",
                    parts,
                },
            ],
        }),
    };

    try {
        const response = await fetch(GEMINI_API_URL, options);
        const data = await response.json();

        if (!response.ok) {
            console.error("Gemini API error:", data);

            throw new Error(
                data.error?.message || "Gemini API request failed"
            );
        }

        const answer =
            data.candidates?.[0]?.content?.parts
                ?.map((part) => part.text || "")
                .join("")
                .trim() || "";

        if (!answer) {
            throw new Error("No response generated by Gemini.");
        }

        return answer;
    } catch (err) {
        console.error("Gemini API error:", err.message);
        throw err;
    }
};

export default getGeminiAPIResponse;
